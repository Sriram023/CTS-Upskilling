public class DataTypeDemo {
    public static void main(String[] args) {
        System.out.println("Java Primitive Data Types");
        System.out.println(); 
        int integera = 100;
        float floatb = 99.5f;
        double doublec = 12345.6789;
        char chard = 'A';
        boolean booleane = true;
        System.out.println("Integer Value : " + integera);
        System.out.println("Float Value   : " + floatb);
        System.out.println("Double Value  : " + doublec);
        System.out.println("Character     : " + chard);
        System.out.println("Boolean Value : " + booleane);
    }
}
